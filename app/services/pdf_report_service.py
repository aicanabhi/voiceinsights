class PDFReportService:

    # =========================================================
    # HELPERS
    # =========================================================

    @staticmethod
    def _format_date(value):
        if value is None:
            return "-"

        if isinstance(value, date):
            return value.strftime("%d %b %Y")

        return str(value)

    @staticmethod
    def _score(value):
        if value is None:
            return "-"

        try:
            return f"{float(value):.2f}"
        except (TypeError, ValueError):
            return str(value)

    @staticmethod
    def _percentage(score):
        """
        Scores in database are 0-10.
        Convert to percentage for visual report.
        """
        if score is None:
            return "-"

        try:
            return f"{float(score) * 10:.1f}%"
        except (TypeError, ValueError):
            return "-"

    @staticmethod
    def _safe_text(value):
        if value is None:
            return ""

        return str(value).replace("&", "&amp;").replace(
            "<", "&lt;"
        ).replace(">", "&gt;")

    # =========================================================
    # HEADER / FOOTER
    # =========================================================

    @staticmethod
    def _header_footer(canvas, doc):
        canvas.saveState()

        width, height = A4

        # Header line
        canvas.setStrokeColor(colors.HexColor("#D1D5DB"))
        canvas.setLineWidth(0.5)

        canvas.line(
            18 * mm,
            height - 12 * mm,
            width - 18 * mm,
            height - 12 * mm,
        )

        # Header text
        canvas.setFont("Helvetica-Bold", 8)
        canvas.setFillColor(colors.HexColor("#1F4E79"))

        canvas.drawString(
            18 * mm,
            height - 9 * mm,
            "VoiceInsights AI",
        )

        canvas.setFont("Helvetica", 8)
        canvas.setFillColor(colors.HexColor("#6B7280"))

        canvas.drawRightString(
            width - 18 * mm,
            height - 9 * mm,
            "Performance Analytics",
        )

        # Footer line
        canvas.setStrokeColor(colors.HexColor("#D1D5DB"))

        canvas.line(
            18 * mm,
            14 * mm,
            width - 18 * mm,
            14 * mm,
        )

        canvas.setFont("Helvetica", 7.5)
        canvas.setFillColor(colors.HexColor("#6B7280"))

        canvas.drawString(
            18 * mm,
            8.5 * mm,
            "Generated by VoiceInsights AI",
        )

        canvas.drawRightString(
            width - 18 * mm,
            8.5 * mm,
            f"Page {doc.page}",
        )

        canvas.restoreState()

