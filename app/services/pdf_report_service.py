    # =========================================================

    @staticmethod
    def _rule_percentage(followed, not_followed):

        try:

            followed = int(followed or 0)
            not_followed = int(not_followed or 0)

            total = followed + not_followed

            if total == 0:
                return "0%"

            return f"{(followed / total) * 100:.1f}%"

        except (TypeError, ValueError):

            return "0%"

    # =========================================================
    # RECOMMENDATIONS
    # =========================================================

    @staticmethod
    def _build_recommendations(report_data):

        summary = report_data.get("summary", {})
        rules = report_data.get("rules", {})
        violations = report_data.get("violations", [])

        recommendations = []

        # Empathy
        empathy = summary.get("average_empathy")

        if empathy is not None:

            try:

                if float(empathy) < 7:

                    recommendations.append(
                        (
                            "High",
                            "Improve empathy and active listening during "
                            "customer interactions, especially when customers "
                            "express financial, emotional, or service-related concerns.",
                        )
                    )

            except (TypeError, ValueError):
                pass

        # Greeting
        greeting_not_followed = int(
            rules.get("greeting_not_followed", 0) or 0
        )

        if greeting_not_followed > 0:

            recommendations.append(
                (
                    "Medium",
                    "Reinforce the standard greeting process and ensure "
                    "agents consistently introduce themselves and establish "
                    "the purpose of the call.",
                )
            )

        # Closing
        closing_not_followed = int(
            rules.get("closing_not_followed", 0) or 0
        )

        if closing_not_followed > 0:

            recommendations.append(
                (
                    "Medium",
                    "Ensure agents provide a clear closing statement, "
                    "confirm that the customer's issue has been addressed, "
                    "and close the interaction professionally.",
                )
            )

        # Violations
        if violations:

            recommendations.append(
                (
                    "Medium",
                    "Review recurring rule violations with agents through "
                    "targeted coaching and call-quality feedback sessions.",
                )
            )

        # Default
        if not recommendations:

            recommendations.append(
                (
                    "Low",
                    "Continue monitoring call quality and maintain regular "
                    "agent coaching based on performance trends.",
                )
            )

        return recommendations